public class For{
    public static void main(String[] args){

     for (int Contagem = 0; Contagem <=9; Contagem++){ //(inicialização; condição; incremento)
               System.out.println(Contagem);  //  Resultado atual
     }
     for (int ContagemRegressiva = 10; ContagemRegressiva >=0; ContagemRegressiva--){ //(inicialização; condição; decremento)
                System.out.println(ContagemRegressiva); //  Resultado atual
     }
    }
   }